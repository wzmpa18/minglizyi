function add(sid, cid, sub, ch, q, opts, ans, expl, diff) {
  // 确保有5个选项
  const defaults = ['以上都不是', '肝气郁结', '脾胃虚弱', '肾阴不足', '活血化瘀', '清热泻火', '疏风解表', '温中散寒', '补益气血'];
  let finalOpts = opts.slice();
  while (finalOpts.length < 5) {
    const extra = defaults[Math.floor(Math.random() * defaults.length)];
    if (!finalOpts.includes(extra) && extra !== ans) finalOpts.push(extra);
  }
  finalOpts = finalOpts.slice(0, 5);
  const idx = finalOpts.indexOf(ans);
  if (idx < 0) {
    finalOpts[4] = ans; // 最后一个位置放正确答案
  }
  const finalIdx = finalOpts.indexOf(ans);
  newQuestions.push({
    id: 'q' + (id++),
    subjectId: sid, chapterId: cid, subject: sub, chapter: ch,
    topic: q.length > 15 ? q.slice(0, 15) : q,
    difficulty: diff || 1,
    question: q,
    options: finalOpts.slice(),
    answer: finalIdx >= 0 ? finalIdx : 0,
    explanation: expl,
    source: '《中医执业医师考试大纲》统编教材'
  });
}

function shuffle(a) {
  const r = [...a];
  for (let i = r.length - 1; i > 0; i--) { const j = Math.floor(Math.random() * (i + 1)); [r[i], r[j]] = [r[j], r[i]]; }
  return r;
}

