function mkQ(subjectId, chapterId, subject, chapter, question, options, answer, explanation, source, difficulty) {
  const answerIdx = options.indexOf(answer);
  return {
    id: nextId(),
    subjectId,
    chapterId,
    subject,
    chapter,
    topic: question.slice(0, 15),
    difficulty: difficulty || 1,
    question,
    options: options.map((o, i) => ['A', 'B', 'C', 'D', 'E'][i] + '. ' + o),
    answer: answerIdx >= 0 ? answerIdx : 0,
    explanation,
    source
  };
}

function shuffle(arr) {
  const result = [...arr];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

