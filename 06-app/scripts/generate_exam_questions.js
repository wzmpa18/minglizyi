  const jichuQ = generateJichuQuestions();
  const zhenduanQ = generateZhenduanQuestions();
  const herbQ = generateHerbQuestions(herbs);
  const formulaQ = generateFormulaQuestions(formulas);
  const acupointQ = generateAcupointQuestions(meridians);

  const allQuestions = [...jichuQ, ...zhenduanQ, ...herbQ, ...formulaQ, ...acupointQ];

