export function getPillarInterpretation(
  pillarLabel: string,
  gan: string,
  zhi: string,
  shishenGan: string,
  nayin: string,
  canggan: string[]
): { pillarLabel: string; items: Array<{ type: string; title: string; content: string; source: string }> } {
  const items: Array<{ type: string; title: string; content: string; source: string }> = [];

  const ganInfo = GAN_INTERPRETATIONS[gan];
  if (ganInfo) {
    items.push({
      type: "gan",
      title: `${gan}（${ganInfo.title}）`,
      content: ganInfo.summary + "\n" + ganInfo.details.slice(0, 2).join("\n"),
      source: ganInfo.source
    });
  }

  const zhiInfo = ZHI_INTERPRETATIONS[zhi];
  if (zhiInfo) {
    items.push({
      type: "zhi",
      title: `${zhi}（${zhiInfo.title}）`,
      content: zhiInfo.summary + "\n" + zhiInfo.details.slice(0, 2).join("\n"),
      source: zhiInfo.source
    });
  }

  const shishenInfo = SHISHEN_INTERPRETATIONS[shishenGan];
  if (shishenInfo) {
    items.push({
      type: "shishen",
      title: `${shishenGan} · ${gan}${zhi}`,
      content: shishenInfo.summary + "\n" + shishenInfo.details.slice(0, 2).join("\n"),
      source: shishenInfo.source
    });
  }

  const nayinInfo = NAYIN_INTERPRETATIONS[nayin];
  if (nayinInfo) {
    items.push({
      type: "nayin",
      title: nayinInfo.title,
      content: nayinInfo.summary,
      source: nayinInfo.source
    });
  }

  if (canggan && canggan.length > 0) {
    const cgDescs = canggan.map(g => {
      const gi = GAN_INTERPRETATIONS[g];
      return gi ? `${g}：${gi.summary.slice(0, 30)}` : g;
    });
    items.push({
      type: "canggan",
      title: `藏干：${canggan.join("、")}`,
      content: `此宫藏${canggan.length}个天干——${canggan.join("、")}。\n${cgDescs.join("\n")}`,
      source: "《三命通会·论人元司事》"
    });
  }

  return { pillarLabel, items };
}

export function getShenshaInterpretation(shenshaName: string): ShenshaInterpretation | null {
  return SHENSHA_INTERPRETATIONS[shenshaName] || null;
}

export function getDayunInterpretation(gan: string, shishenGan: string): string {
  const shishenInfo = SHISHEN_INTERPRETATIONS[shishenGan];
  const ganInfo = GAN_INTERPRETATIONS[gan];
  if (!shishenInfo || !ganInfo) return "";
  return `大运天干${gan}（${ganInfo.title}），为日主之${shishenGan}。${shishenInfo.summary} 此十年运程受${shishenGan}影响，${shishenInfo.details[0]}`;
}