/** 获取干支解读 */
export function getCalendarGanzhiInterpretation(ganzhi: string): { title: string; items: CalendarInterpretItem[] } | null {
  const info = GANZHI_DETAILS[ganzhi];
  if (!info) {
    return {
      title: ganzhi + " · 干支解读",
      items: [{
        type: "ganzhi",
        title: ganzhi + "解读",
        content: ganzhi + "为六十甲子之一，蕴含天地阴阳五行之变化。具体吉凶需结合八字整体判断。",
        source: "《协纪辨方书》",
      }],
    };
  }

  return {
    title: ganzhi + " · 干支解读",
    items: [{
      type: "ganzhi",
      title: ganzhi + "解读",
      content: info.summary + "\n" + info.details.join("\n"),
      source: "《协纪辨方书》",
    }],
  };
}

