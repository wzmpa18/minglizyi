export interface LiuyaoInterpretItem {
  type: "gua" | "shen" | "qin" | "shiyin" | "dongyao";
  title: string;
  content: string;
  source: string;
}

/** 获取卦名解读 */
export function getGuaInterpretation(guaName: string): { items: LiuyaoInterpretItem[] } | null {
  const info = GUA_INTERPRETATIONS[guaName];
  if (!info) return null;
  return {
    items: [{
      type: "gua",
      title: info.title,
      content: info.summary + "\n" + info.details.join("\n"),
      source: info.source,
    }],
  };
}

/** 获取六神解读 */
export function getLiuShenInterpretation(shenName: string): { items: LiuyaoInterpretItem[] } | null {
  const info = LIUSHEN_INTERPRETATIONS[shenName];
  if (!info) return null;
  return {
    items: [{
      type: "shen",
      title: shenName + " · 六神",
      content: info.summary + "\n" + info.details.join("\n"),
      source: info.source,
    }],
  };
}

/** 获取爻位解读（含六亲+世应+动爻） */
export function getYaoInterpretation(
  yaoIndex: number,
  liuQin: string,
  liuShen: string,
  isShi: boolean,
  isYing: boolean,
  isDong: boolean,
  gan: string,
  zhi: string,
): { yaoLabel: string; items: LiuyaoInterpretItem[] } {
  const items: LiuyaoInterpretItem[] = [];
  const yaoName = ["初爻", "二爻", "三爻", "四爻", "五爻", "上爻"][yaoIndex];

  // 六亲解读
  const qinInfo = LIUQIN_INTERPRETATIONS[liuQin];
  if (qinInfo) {
    items.push({
      type: "qin",
      title: liuQin + " · " + gan + zhi,
      content: qinInfo.summary + "\n" + qinInfo.details.join("\n"),
      source: qinInfo.source,
    });
  }

  // 六神解读
  const shenInfo = LIUSHEN_INTERPRETATIONS[liuShen];
  if (shenInfo) {
    items.push({
      type: "shen",
      title: liuShen + "临" + yaoName,
      content: shenInfo.summary + "\n" + shenInfo.details.join("\n"),
      source: shenInfo.source,
    });
  }

  // 世应解读
  if (isShi) {
    const shiInfo = SHIYING_INTERPRETATIONS["世"];
    items.push({
      type: "shiyin",
      title: "世爻 · " + yaoName,
      content: shiInfo.summary + "\n" + shiInfo.details.join("\n"),
      source: shiInfo.source,
    });
  } else if (isYing) {
    const yingInfo = SHIYING_INTERPRETATIONS["应"];
    items.push({
      type: "shiyin",
      title: "应爻 · " + yaoName,
      content: yingInfo.summary + "\n" + yingInfo.details.join("\n"),
      source: yingInfo.source,
    });
  }

  // 动爻解读
  if (isDong) {
    items.push({
      type: "dongyao",
      title: "动爻 · " + yaoName,
      content: "此爻发动，为变化之机。动爻为事之关键，主事情将有变动。\n" +
        "动爻化进神：主事情向好的方向发展，如官动化进则升迁。\n" +
        "动爻化退神：主事情向差的方向发展，宜及时止损。\n" +
        "动爻化回头克：主事情有变数，先吉后凶或先凶后吉。\n" +
        "动爻化空亡：主变动落空，最终无果。",
      source: "《增删卜易·动变章》",
    });
  }

  return { yaoLabel: yaoName + "解读", items };
}