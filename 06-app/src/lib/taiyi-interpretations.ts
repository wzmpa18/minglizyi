/** 获取太乙宫位解读 */
export function getTaiyiPalaceInterpretation(gong: number): { title: string; items: TaiyiInterpretItem[] } | null {
  const info = TAIYI_PALACE_DETAILS[gong];
  if (!info) return null;

  return {
    title: `第${gong}宫 · ${info.bagua}宫 · ${info.direction}`,
    items: [{
      type: "palace",
      title: `${info.bagua}宫（${info.wuxing}）解读`,
      content: info.summary + "\n" + info.details.join("\n"),
      source: "《太乙金镜式经》",
    }],
  };
}

/** 获取太乙十六神解读 */
export function getTaiyiShenInterpretation(shenName: string): { title: string; items: TaiyiInterpretItem[] } | null {
  const info = TAIYI_SHEN_DETAILS[shenName];
  if (!info) return null;

  return {
    title: shenName + " · 十六神解读",
    items: [{
      type: "star",
      title: shenName,
      content: info.summary + "\n" + info.details.join("\n"),
      source: "《太乙统宗宝鉴》",
    }],
  };
}