/** 获取掌诀解读 */
export function getXiaoliurenInterpretation(palmName: string): { title: string; items: XiaoliurenInterpretItem[] } | null {
  const info = PALM_DETAILS[palmName];
  if (!info) return null;

  return {
    title: info.title,
    items: [{
      type: "palm",
      title: info.name + " · 掌诀解读",
      content: info.summary + "\n" + info.details.join("\n"),
      source: info.source,
    }],
  };
}