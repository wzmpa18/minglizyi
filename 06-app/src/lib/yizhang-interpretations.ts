/** 获取宫位解读 */
export function getYizhangPalaceInterpretation(zhi: string): { title: string; items: YizhangInterpretItem[] } | null {
  const info = PALACE_DETAILS[zhi];
  if (!info) return null;

  return {
    title: `${zhi} · ${info.name} · ${info.type}`,
    items: [
      {
        type: "palace",
        title: `${info.name}宫解读`,
        content: info.summary + "\n" + info.details.join("\n"),
        source: "《达摩一掌经》",
      },
      {
        type: "liudao",
        title: info.type + "之道",
        content: LIUDAO_DETAILS[info.type]?.summary + "\n" + (LIUDAO_DETAILS[info.type]?.details.join("\n") || ""),
        source: "《一掌经金口诀》",
      },
    ],
  };
}

/** 获取六道解读 */
export function getYizhangLiudaoInterpretation(liudao: string): { title: string; items: YizhangInterpretItem[] } | null {
  const info = LIUDAO_DETAILS[liudao];
  if (!info) return null;

  return {
    title: liudao + " · 六道解读",
    items: [{
      type: "liudao",
      title: liudao + "之道",
      content: info.summary + "\n" + info.details.join("\n"),
      source: "《一掌经金口诀》",
    }],
  };
}