async function main() {
  const db = new Database(process.env.DB_PATH);
  db.prepare(
    "INSERT OR REPLACE INTO users (user_id, phone, password_hash, nickname, member_level, membership_expiry, status) VALUES (?,?,?,?,?,?,'active')"
  ).run(UID, '00000000000', 'gate-verify-only', 'gate_verify_tmp', 'monthly', '2027-12-31 23:59:59');

  const token = jwt.sign({ userId: UID }, process.env.JWT_SECRET, { expiresIn: 900 });
  const t0 = Date.now();

  const res = await fetch(`${API}/ai/chat`, {
    method: 'POST',
    headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      systemPrompt: SYSTEM_PROMPT,
      userPrompt: USER_PROMPT,
      requestId: 'bazi-prompt-verify-' + Date.now(),
    }),
  });
  const j = await res.json();
  console.log(`[1] POST /api/ai/chat: HTTP ${res.status} success=${j.success} 耗时${Date.now() - t0}ms`);
  if (!j.success) { console.log(JSON.stringify(j).slice(0, 500)); throw new Error('AI 调用失败'); }

  const c = j.content || '';
  const len = c.length;
  console.log(`[2] 输出字数: ${len}`);

  const checks = {
    '第一部分': c.includes('第一部分'),
    '第二部分': c.includes('第二部分'),
    '第三部分': c.includes('第三部分'),
    '第四部分': c.includes('第四部分'),
    '格局核心总论': c.includes('格局核心总论'),
    '大运逐段详解': c.includes('大运逐段详解'),
    '婚姻感情': c.includes('婚姻感情'),
    '财运事业': c.includes('财运事业'),
    '学业文昌': c.includes('学业文昌'),
    '健康体质': c.includes('健康体质'),
    '典籍末标': c.includes('以上分析参考《三命通会》《渊海子平》《穷通宝鉴》《神峰通考》等传统命理学古籍，仅为国学文史研究参考。'),
    '大运段数>=8': (c.match(/大运（\d+-\d+岁）|运（\d+-\d+岁）/g) || []).length >= 8 || (c.match(/（\d+-\d+岁）/g) || []).length >= 8,
    '字数>=1200': len >= 1200,
    '无研习建议': !c.includes('研习建议'),
  };
  const forbidden = ['大凶', '破财', '灾病', '灾难', '克夫', '克妻', '克子', '短命', '注定'].filter(w => c.includes(w));
  checks['无恐吓词'] = forbidden.length === 0;

  let allOk = true;
  for (const [k, v] of Object.entries(checks)) {
    console.log(`  ${v ? 'PASS' : 'FAIL'}  ${k}`);
    if (!v) allOk = false;
  }
  if (forbidden.length) console.log('  命中恐吓词:', forbidden.join(','));

  console.log('--- 输出预览（前600字）---');
  console.log(c.slice(0, 600));
  console.log('--- 输出结尾（后300字）---');
  console.log(c.slice(-300));

  db.prepare('DELETE FROM users WHERE user_id = ?').run(UID);
  db.close();
  console.log('[3] 临时用户已清理');
  console.log(allOk ? 'AI_PROMPT_TEST_OK' : 'AI_PROMPT_TEST_FAIL');
}

main().catch((e) => { console.error('AI_PROMPT_TEST_FAIL:', e.message); process.exit(1); });
