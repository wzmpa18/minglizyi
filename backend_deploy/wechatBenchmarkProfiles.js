// 批次日（1/8/15/22）与节气对齐：批次日距节气 ±3 天内出节气文（措辞自适应：将至/当天/刚过）
function solarTermForBatch(runDate) {
  const d = new Date(runDate + 'T00:00:00');
  for (const st of SOLAR_TERMS) {
    const td = new Date(st.date + 'T00:00:00');
    const diff = (td - d) / 86400000; // 正数=节气在未来
    if (diff >= -3 && diff <= 3) return st;
  }
  return null;
}

