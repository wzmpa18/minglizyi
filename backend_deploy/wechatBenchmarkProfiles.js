// 把 CRAFT 摊平成可注入 prompt 的要点串
function craftBullets() {
  return [
    '开场：' + CRAFT.hook,
    '密度：' + CRAFT.density,
    '结构：' + CRAFT.oneIdea,
    '证据：' + CRAFT.evidence,
    '金句：' + CRAFT.oneLiner,
    '语感：' + CRAFT.antiAi,
    '收尾：' + CRAFT.close,
    '原创合规：' + CRAFT.originality,
    '零推广：' + CRAFT.noPromo,
  ].join('\n');
}

