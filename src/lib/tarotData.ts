function buildMajor(): TarotCard[] {
  return MAJOR.map(([num, name, nameEn, uk, rk, up, rev]) => ({
    id: `major-${String(num).padStart(2, "0")}`,
    num, suit: "major" as TarotSuit, suitName: "大阿卡纳",
    name, nameEn, element: "综合",
    uprightKeywords: uk, reversedKeywords: rk, upright: up, reversed: rev,
  }));
}

function buildMinor(defs: MinorDef[], suit: TarotSuit, element: string): TarotCard[] {
  return defs.map((d) => ({
    id: `${suit}-${d.s}`,
    num: parseInt(d.s, 10),
    suit, suitName: SUIT_NAMES[suit],
    name: d.n, nameEn: "",
    element,
    uprightKeywords: d.uk, reversedKeywords: d.rk,
    upright: d.up, reversed: d.rev,
  }));
}

export const TAROT_CARDS: TarotCard[] = [
  ...buildMajor(),
  ...buildMinor(WANDS, "wands", "火"),
  ...buildMinor(CUPS, "cups", "水"),
  ...buildMinor(SWORDS, "swords", "风"),
  ...buildMinor(PENTACLES, "pentacles", "土"),
];

export const TAROT_CARD_MAP: Record<string, TarotCard> = Object.fromEntries(
  TAROT_CARDS.map((c) => [c.id, c])
);

export function getCard(id: string): TarotCard | undefined {
  return TAROT_CARD_MAP[id];
}

