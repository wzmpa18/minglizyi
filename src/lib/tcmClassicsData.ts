/** 获取所有典籍 */
export function getAllClassics(): TCMClassic[] {
  return TCM_CLASSICS;
}

/** 根据 ID 获取典籍 */
export function getClassicById(id: string): TCMClassic | undefined {
  return TCM_CLASSICS.find((c) => c.id === id);
}

/** 根据分类获取典籍列表 */
export function getClassicsByCategory(category: TCMClassic['category']): TCMClassic[] {
  return TCM_CLASSICS.filter((c) => c.category === category);
}

/** 获取免费典籍 */
export function getFreeClassics(): TCMClassic[] {
  return TCM_CLASSICS.filter((c) => c.isFreeContent);
}

/** 获取会员专享典籍 */
export function getMemberClassics(): TCMClassic[] {
  return TCM_CLASSICS.filter((c) => !c.isFreeContent);
}

/** 搜索典籍内容 */
export function searchClassicsContent(keyword: string): TCMClassic[] {
  if (!keyword.trim()) return [];
  const lower = keyword.toLowerCase();
  return TCM_CLASSICS.filter((c) => {
    return (
      c.title.toLowerCase().includes(lower) ||
      c.author.toLowerCase().includes(lower) ||
      c.summary.toLowerCase().includes(lower) ||
      c.chapters.some(
        (ch) =>
          ch.title.includes(keyword) ||
          ch.content.includes(keyword) ||
          ch.annotation.includes(keyword)
      )
    );
  });
}

/** 获取典籍总章节数 */
export function getTotalChapterCount(): number {
  return TCM_CLASSICS.reduce((sum, c) => sum + c.chapters.length, 0);
}

