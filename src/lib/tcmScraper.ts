// ==================== localStorage 缓存（带TTL） ====================
const LOCAL_CACHE_KEY = "tcm_scrape_cache";
const CACHE_TTL_MS = 7 * 24 * 60 * 60 * 1000; // 缓存有效期：7天

interface CacheEntry {
  data: ScrapeResult;
  cachedAt: number; // 缓存时间戳
}

function getLocalCache(): Record<string, CacheEntry> {
  try {
    const raw = localStorage.getItem(LOCAL_CACHE_KEY);
    return raw ? JSON.parse(raw) : {};
  } catch {
    return {};
  }
}

function setLocalCacheEntry(id: string, data: ScrapeResult): void {
  const cache = getLocalCache();
  cache[id] = { data, cachedAt: Date.now() };
  try {
    localStorage.setItem(LOCAL_CACHE_KEY, JSON.stringify(cache));
  } catch { /* ignore */ }
}

