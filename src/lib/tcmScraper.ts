/** 获取已缓存的穴位信息（带TTL检查） */
export function getCachedAcupointInfo(
  id: string,
  type: "acupoint" | "dong" = "acupoint"
): ScrapeResult | null {
  const local = getLocalCache();
  const entry = local[id];
  if (!entry) return null;
  // 检查缓存是否过期
  if (Date.now() - entry.cachedAt > CACHE_TTL_MS) {
    // 缓存已过期，清除并返回null
    delete local[id];
    try {
      localStorage.setItem(LOCAL_CACHE_KEY, JSON.stringify(local));
    } catch { /* ignore */ }
    return null;
  }
  return entry.data;
}

/** 获取穴位信息（静态数据，无需网络请求），自动使用缓存 */
export function triggerScrape(
  id: string,
  name: string,
  meridian: string,
  type: "acupoint" | "dong" = "acupoint"
): ScrapeResult | null {
  // 先检查缓存
  const cached = getCachedAcupointInfo(id, type);
  if (cached) return cached;
  // 缓存未命中或已过期，重新生成并缓存
  const result = buildResult(name, meridian);
  setLocalCacheEntry(id, result);
  return result;
}

/** 标记需要重新抓取（清除缓存，下次获取时重新生成） */
export function markForRefetch(
  id: string,
  type: "acupoint" | "dong" = "acupoint"
): boolean {
  const cache = getLocalCache();
  if (cache[id]) {
    delete cache[id];
    try {
      localStorage.setItem(LOCAL_CACHE_KEY, JSON.stringify(cache));
    } catch { /* ignore */ }
    return true;
  }
  return false;
}

export function getLocalCachedInfo(id: string): ScrapeResult | null {
  return getCachedAcupointInfo(id);
}

export function setLocalCachedInfo(id: string, data: ScrapeResult): void {
  setLocalCacheEntry(id, data);
}

/** 清除所有过期的缓存条目（可定期调用以释放存储空间） */
export function cleanExpiredCache(): number {
  const cache = getLocalCache();
  let cleaned = 0;
  for (const key of Object.keys(cache)) {
    if (Date.now() - cache[key].cachedAt > CACHE_TTL_MS) {
      delete cache[key];
      cleaned++;
    }
  }
  if (cleaned > 0) {
    try {
      localStorage.setItem(LOCAL_CACHE_KEY, JSON.stringify(cache));
    } catch { /* ignore */ }
  }
  return cleaned;
}