/** 获取建除十二神解读 */
export function getZeriJianchuInterpretation(jianchu: string): { title: string; items: ZeriInterpretItem[] } | null {
  const info = JIANCHU_DETAILS[jianchu];
  if (!info) return null;

  return {
    title: jianchu + "日 · " + info.jixiong,
    items: [{
      type: "jianchu",
      title: jianchu + "日解读",
      content: info.summary + "\n" + info.details.join("\n"),
      source: "《协纪辨方书》",
    }],
  };
}

