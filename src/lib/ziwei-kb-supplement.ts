export function getKbStarNote(star: string): KbStarNote | null {
  return KB_STAR_NOTES.find(n => n.star === star) || null;
}

export function getKbAuxStarNote(star: string): KbAuxStarNote | null {
  return KB_AUX_STAR_NOTES.find(g => g.stars.includes(star)) || null;
}

export function getKbStarPalaceSupplement(star: string, palace: string): string {
  const hit = KB_STAR_PALACE_SUPPLEMENTS.find(s => s.star === star && (s.palace === palace || s.palace + "宫" === palace));
  return hit ? hit.interpretation : "";
}

